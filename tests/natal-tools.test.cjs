const assert=require('node:assert/strict');
const Tools=require('../public/natal-tools.js'),Core=require('../public/natal-core.js');
const birth=Core.calculate({date:'1997-08-14',time:'06:24',zone:'America/Denver',lat:39.7392,lon:-104.9903,houses:'whole',unknown:false});
const original=JSON.stringify(birth);
const same=Tools.transit('1997-08-14','12:24',birth.planets,3);
assert.deepEqual(same.planets,birth.planets);
assert.equal(same.aspects.filter(a=>a.a===a.b&&a.name==='Conjunction'&&a.orb===0).length,10);
const later=Tools.transit('1997-08-15','12:24',birth.planets,3);
assert.ok(Core.delta(later.planets[0].longitude,same.planets[0].longitude)>.9);
assert.equal(JSON.stringify(birth),original);
const wrapped=Tools.crossAspects([{longitude:359}],[{longitude:1}],2);
assert.equal(wrapped[0].name,'Conjunction');assert.equal(wrapped[0].orb,2);
assert.equal(Tools.crossAspects([{longitude:359}],[{longitude:1}],1).length,0);
assert.equal(Tools.crossAspects([{longitude:90}],[{longitude:0}],0)[0].name,'Square');
assert.throws(()=>Tools.transit('2025-02-30','12:00',birth.planets));
assert.throws(()=>Tools.transit('2025-02-20','25:00',birth.planets));
assert.throws(()=>Tools.transit('1899-02-20','12:00',birth.planets));
assert.throws(()=>Tools.crossAspects([],[],11));
console.log('PASS: transit positions, natal invariance, identity conjunctions, date changes, angular wrap, orb boundaries and input limits.');
