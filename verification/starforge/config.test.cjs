const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const defaults={tier:'soulseed',palette:'violet',stars:'gold',density:36,lines:'orbits',decor:'moon',light:65,motion:false};
const ctx=vm.createContext({universeDefaults:()=>({cosmetics:{...defaults}}),forgeDraft:{...defaults},worldState:{still:false},applyHubCosmetics:()=>{}});
vm.runInContext(fs.readFileSync('dist/starforge.js','utf8'),ctx);
const config=x=>ctx.forgeConfig(x),effective=x=>ctx.forgeEffective(x);
assert.equal(config({...defaults,motion:true}).motionLevel,'gentle','legacy motion migrates');
assert.equal(config({...defaults,density:500}).density,100);
assert.equal(config({...defaults,light:-5}).light,35);
assert.equal(config({...defaults,avatarColor:'invalid'}).avatarColor,'violet');
const draft=config({...defaults,tier:'pro',palette:'rose',avatarColor:'gold',density:100,decor:'planet',pattern:'lattice',motionLevel:'flow'});
assert.equal(effective({...draft,tier:'soulseed'}).palette,'violet');
assert.equal(effective({...draft,tier:'soulseed'}).density,28);
assert.equal(effective({...draft,tier:'bloom'}).pattern,'wings');
assert.equal(effective({...draft,tier:'bloom'}).avatarColor,'violet');
assert.equal(effective({...draft,tier:'bloom'}).motion,false);
assert.equal(effective(draft).avatarColor,'gold');
assert.equal(draft.pattern,'lattice','tier comparison leaves original draft intact');
for(const type of ['pinpoint','crystal','mixed'])assert.equal((ctx.forgeParticles({...draft,starType:type}).match(/class="sf-star(?: |")/g)||[]).length,100);
for(const pattern of ['meridian','wings','lattice'])assert.ok(ctx.forgeAvatar({...draft,pattern}).includes(`data-pattern="${pattern}"`));
ctx.worldState.still=true;
assert.ok(ctx.forgeAvatar(draft).includes('data-animated="false"'));
assert.ok(ctx.forgeEnvironment(draft).includes('data-motion="false"'));
assert.ok(fs.readFileSync('dist/starforge.css','utf8').includes('@media(prefers-reduced-motion:reduce)'));
assert.ok(!fs.readFileSync('dist/starforge.js','utf8').includes('universeSession.entitlement='));
console.log('PASS: migration, tier constraints, preserved draft, star density, patterns, motion override and cosmetic-only ownership boundary.');
