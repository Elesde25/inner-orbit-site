export const CITIES: City[] = ROWS.map(([id, name, country, lat, lon, tz, hub]) => ({
  id, name, country, lat, lon, tz, hub: hub === 1,
}));

const norm = (s: string) =>
  s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");

/** Ranked type-ahead: prefix → word-start → substring → country. Empty query → hub cities. */
export function searchCities(query: string, limit = 8): City[] {
  const q = norm(query.trim());
  if (!q) return CITIES.filter((c) => c.hub).slice(0, limit);
  const scored: { c: City; rank: number }[] = [];
  for (const c of CITIES) {
    const name = norm(c.name);
    const country = norm(c.country);
    let rank = -1;
    if (name.startsWith(q)) rank = 0;
    else if (name.split(/[\s.\-]+/).some((w) => w.startsWith(q))) rank = 1;
    else if (name.includes(q)) rank = 2;
    else if (country.includes(q)) rank = 3;
    if (rank >= 0) scored.push({ c, rank });
  }
  scored.sort((a, b) => a.rank - b.rank || a.c.name.localeCompare(b.c.name));
  return scored.slice(0, limit).map((s) => s.c);
}
